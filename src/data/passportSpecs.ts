/**
 * Look up a spec by country code. Falls back to DEFAULT_SPEC.
 */
export function getSpecByCode(code: string): PassportSpec {
  return (
    PASSPORT_SPECS.find(
      (s) => s.countryCode.toUpperCase() === code.toUpperCase(),
    ) ?? DEFAULT_SPEC
  );
}